                WHEN 'NENTANG' THEN 1 WHEN 'CL1' THEN 1
                WHEN 'INTERMEDIATE' THEN 2 WHEN 'APPLY' THEN 2
                WHEN 'APDUNG' THEN 2 WHEN 'CL2' THEN 2
