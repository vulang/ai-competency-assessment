                WHEN 'KIENTAO' THEN 3 WHEN 'CL3' THEN 3
            END AS mapped_level
        FROM questions q
        LEFT JOIN skills s ON s.skill_id = q.skill_id
        LEFT JOIN domains d ON d.domain_id = s.domain_id
    )
